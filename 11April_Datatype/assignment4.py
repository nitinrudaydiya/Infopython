'''
Assignment 4: Area of Rectangle

Write a Python program that:

Accepts length and breadth.
Calculates area.

Input:
Length = 10
Breadth = 5

Output:
Area = 50
------------------------------------------------
'''
Length = float(input("Length = "))
Breadth = float(input("Breadth = "))
area = Length*Breadth
print(f"Area = {area}")